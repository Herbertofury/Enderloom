'use strict';
const assert=require('assert/strict'),fs=require('fs'),os=require('os'),path=require('path');
const {LauncherService}=require('../src/launcher-service');const {seedProjectContext}=require('./project-context-fixtures');
const root=path.resolve(__dirname,'..'),temporary=fs.mkdtempSync(path.join(os.tmpdir(),'enderloom-config-owner-'));
const service=new LauncherService({rootDir:root,dataDir:path.join(temporary,'data')});
(async()=>{
 const {first}=await seedProjectContext(service);
 const scan=await service.request('scan_instance_workbench',{instanceId:first.id,includeMods:false});
 const owner=p=>scan.entries.find(e=>e.path===p).owner;
 assert.equal(owner('config/identity_fixture-client.toml').file_name,'first.jar');
 assert.equal(owner('config/identity_fixture_plus-client.toml').id,'identity_fixture_plus');
 assert.equal(owner('saves/identity_fixture/serverconfig/helper-server.toml').id,'helper');
 assert.equal(owner('config/shared-title.json').confidence,'unassigned');
 const preference=(p,v)=>service.request('creative_library_action',{operation:'preferences',payload:{['config-owner:'+first.id+':'+p]:v}});
 await preference('config/custom.json','identity_fixture');
 const manual=await service.request('scan_instance_workbench',{instanceId:first.id,includeMods:false,quick:true});assert.equal(manual.entries.find(e=>e.path==='config/custom.json').owner.confidence,'manual');
 await preference('config/identity_fixture-client.toml','unassigned');
 await preference('config/custom.json','removed_mod');
 const corrected=await service.request('scan_instance_workbench',{instanceId:first.id,includeMods:false,quick:true});
 assert.equal(corrected.entries.find(e=>e.path==='config/identity_fixture-client.toml').owner.id,'unassigned');
 assert.equal(corrected.entries.find(e=>e.path==='config/custom.json').owner.reason,'Your assigned mod is no longer installed.');
 assert.equal(corrected.entries.find(e=>e.path==='config/identity_fixture-client.toml').automatic_owner.id,'identity_fixture');
 console.log('PASS native Config ownership: enabled/disabled copies, sibling identity, world scopes, ambiguous titles, persisted corrections and separate automatic suggestion.');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>service.close());
