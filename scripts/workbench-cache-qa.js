'use strict';
const assert = require('assert/strict'), fs = require('fs'), path = require('path'), vm = require('vm');
const ts = require('../launcher/node_modules/typescript');
const source = ts.transpileModule(fs.readFileSync(path.join(__dirname,'../launcher/src/lib/workbench-cache.ts'),'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const calls = [], pending = [], exports_ = {};
const api = {scanWorkbench:(id, scope, quick=false)=>{calls.push({id,scope,quick});return new Promise((resolve,reject)=>pending.push({resolve,reject}));},listInstanceContent:async()=>[]};
vm.runInNewContext(source,{exports:exports_,require:()=>({api})});
const turn = ()=>new Promise(resolve=>setImmediate(resolve));
(async()=>{
  const a=[], b=[];
  const first=exports_.scanWorkbenchShared('one',false,v=>a.push(v));
  const second=exports_.scanWorkbenchShared('one',false,v=>b.push(v));
  assert.equal(calls.length,1,'Concurrent opens share their inventory request');
  pending.shift().resolve({entries:[{path:'old'}],scanned_at:1}); await turn();
  assert.equal(a.length,1); assert.equal(b.length,1); assert.equal(calls.length,2);
  const reopened=[];
  const third=exports_.scanWorkbenchShared('one',false,v=>reopened.push(v));
  assert.equal(reopened.length,1,'Returning to a loading tab immediately shows its inventory');
  assert.equal(calls.length,2,'Navigation does not queue another full scan');
  pending.shift().resolve({entries:[{path:'checked'}],scanned_at:2}); await Promise.all([first,second,third]);
  const warm=[];
  const fourth=exports_.scanWorkbenchShared('one',false,v=>warm.push(v));
  assert.equal(warm[0].scanned_at,2); assert.equal(calls.at(-1).quick,false,'Warm refresh does not replace verified rows with an unchecked inventory');
  const changed=exports_.refreshWorkbenchAfterChange('one',false,()=>{});
  pending.shift().resolve({entries:[],scanned_at:3}); await fourth; await turn();
  assert.equal(calls.length,4,'A mutation forces a pass newer than the running scan');
  pending.shift().resolve({entries:[{path:'new'}],scanned_at:4}); await changed;
  assert.equal(exports_.workbenchSnapshot('one',false).scanned_at,4);
  const fail=exports_.scanWorkbenchShared('two',false,()=>{}); const failure=assert.rejects(fail,/offline/);
  pending.shift().reject(new Error('offline')); await failure;
  assert.equal(exports_.workbenchSnapshot('two',false),null,'Profiles cannot inherit each other’s rows');
  const retry=exports_.scanWorkbenchShared('two',false,()=>{});
  pending.shift().resolve({entries:[],scanned_at:5}); await turn();
  pending.shift().resolve({entries:[],scanned_at:6}); await retry;
  assert.equal(exports_.workbenchSnapshot('one',true),null,'Lineage scope has its own complete inventory');
  console.log('PASS Config shared requests, instant warm inventory, mutation ordering, profile/scope isolation and error recovery.');
})().catch(e=>{console.error(e);process.exitCode=1;});
