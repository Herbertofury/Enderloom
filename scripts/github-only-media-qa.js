'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const main=fs.readFileSync(path.join(root,'main.js'),'utf8');
const app=fs.readFileSync(path.join(root,'catalog/app.js'),'utf8');
const enhance=fs.readFileSync(path.join(root,'catalog/enhance.js'),'utf8');
const provider=fs.readFileSync(path.join(root,'src/provider-media.js'),'utf8');
assert(main.includes('https://opengraph.githubassets.com/mcc-live/'),'GitHub repository page preview is missing');
assert(main.includes('.png?size=160')&&main.includes("source:'github-owner-avatar'"),'exact GitHub owner avatar is missing');
assert(main.includes('githubOwnerExact:true'),'GitHub owner identity cannot override a stale imported author');
assert(main.includes('exclusive:context.githubOnly===true'),'GitHub-only repository preview can still be replaced by unrelated deep media');
assert(main.includes("if(extra.githubOnly===true){target.gallery=[];target.icon=null;target.author=null;target.authorUrl='';target.exclusive=true;}"),'GitHub-only media does not evict stale cached roles');
assert(app.includes('function githubOnlyProject(p)')&&app.includes('data-github-only'),'Catalog does not mark GitHub-only entries');
assert(enhance.includes('githubOnly:!!s.githubOnly'),'GitHub-only identity is not sent to media discovery');
assert(provider.includes("context.githubOnly?'github-only':''"),'GitHub-only caches are not isolated');
assert(!main.includes('capturePage()'),'GitHub preview regressed to an opaque page screenshot');
console.log(JSON.stringify({passed:true,preview:'GitHub OpenGraph repository page',author:'exact repository owner avatar',staleCacheEviction:true,deepReplacementBlocked:true},null,2));
